export const DICT: Record<Lang, Record<Key, string>> = { en, he };
export type TKey = Key;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
	let s = DICT[lang][key];
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}

/** Wraps text in Unicode isolates (for share text, never JSX). */
export const isolate = (s: string | number) => `\u2068${s}\u2069`;

export function usePrefs() {
	const { prefs } = useRouteContext({ from: '__root__' });
	const router = useRouter();

	const setLang = useCallback(
		(lang: Lang) => {
			writePrefCookie(LANG_COOKIE, lang);
			document.documentElement.lang = lang;
			document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
			void router.invalidate();
		},
		[router],
	);

	const setTheme = useCallback(
		(theme: ThemePref) => {
			writePrefCookie(THEME_COOKIE, theme);
			if (theme === 'system') delete document.documentElement.dataset.theme;
			else document.documentElement.dataset.theme = theme;
			window.dispatchEvent(new Event('fe-theme'));
			void router.invalidate();
		},
		[router],
	);

	return { ...prefs, setLang, setTheme };
}

export function useT() {
	const { lang } = usePrefs();
	const t = useCallback((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
	return { t, lang };
}
